import assert from "node:assert/strict";
import fs from "node:fs";
const source=fs.readFileSync("src/features/iam/api/iiamApi.js","utf8");
const {createIiamApi,PLATFORM_SCOPE}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const identity="11111111-1111-4111-8111-111111111111", application="22222222-2222-4222-8222-222222222222";
let call;
const api=createIiamApi(async(path,options)=>{call={path,...options};return {items:[],total:0};});
await api.approve(application,identity,{type:"EMPLOYEE",registration:"BUSINESS-007"});
assert.equal(call.path,`/api/iam/api/v1/admin/identity-applications/${application}/approve`);
assert.deepEqual(call.body,{tenantId:identity,affiliation:{type:"EMPLOYEE",registration:"BUSINESS-007"}});
assert.equal(call.authenticated,true);
await api.endSession(identity);assert.equal(call.method,"DELETE");assert.equal(call.path,`/api/iam/authentication/sessions/${identity}`);
await api.endAdminSession(42);assert.equal(call.method,"PATCH");assert.equal(call.path,"/api/iam/authentication/admin/sessions/42/logout");
await api.saveRolePermissions({id:3,version:7,password:"must-not-leak"},["logimarui-core.services.read"],"Reviewed access");
assert.equal(call.method,"PUT");assert.equal(call.body.version,7);assert.equal(call.body.reason,"Reviewed access");
assert.deepEqual(call.body.permissions,["logimarui-core.services.read"]);assert.equal(call.body.password,undefined);
assert.match(call.body.correlationId,/^[0-9a-f-]{36}$/);
await api.assign(identity,3,PLATFORM_SCOPE,"Approved assignment");assert.equal(call.body.identityId,identity);assert.equal(call.body.roleId,3);
await api.revokeAssignment({id:identity,version:9},"Revoked assignment");assert.equal(call.body.version,9);
assert.throws(()=>api.identity(42),/UUID/);assert.throws(()=>api.endSession(42),/UUID/);assert.throws(()=>api.endAdminSession(identity),/perfil válido/);
assert.throws(()=>api.saveRolePermissions({id:3},[],"Review"),/versão/);assert.throws(()=>api.deny(identity,"permission",PLATFORM_SCOPE,""),/motivo/);
